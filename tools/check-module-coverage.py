#!/usr/bin/env python3
"""Which ported modules actually reach the shipped library, and which are referenced from C.

A module can be written, verified in isolation, listed in a build script and still not be part of the
runtime: the GGUF reader and the detokenizer were both built and called by nothing (EXP-2026-11-19-1314).
This reads the repository for `export fn` names and the built libraries for their symbols, and reports
per module how many of its doors are present.

"Referenced" means the name appears in a C/C++ source or in the shim that generates C - a direct call or a
dlsym string. A dlsym string counts even when the call is made only under a diagnostic flag, so this column
is an upper bound on being reached, not proof. Presence without reference is the state the detokenizer and
the GGUF reader were both in.
"""
import re
import subprocess
import sys
import pathlib
from collections import defaultdict

BIN = sys.argv[1] if len(sys.argv) > 1 else "builds/flint-acc/bin"
ROOT = pathlib.Path(__file__).resolve().parent.parent

def library_symbols():
    syms = set()
    for so in pathlib.Path(BIN).glob("*.so*"):
        out = subprocess.run(f"nm -D --defined-only {so}", shell=True, capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1] in ("T", "W"):
                syms.add(parts[2])
    return syms

def referenced_symbols():
    """Names that appear in C/C++ sources - a direct call or a dlsym string. Presence in the binary is not
    the same as being reached, and this is the cheapest way to tell the two apart without running anything."""
    seen = set()
    # The sampler doors are reached through a shim that is generated by a shell script, and the generated C
    # lives under build/. Scanning only runtime/vendor/integration reported the sampler chain as never called,
    # which was wrong the first time this tool ran.
    roots = [ROOT / "runtime", ROOT / "vendor", ROOT / "integration", ROOT / "tools", ROOT / "build"]
    for root in roots:
        if not root.is_dir():
            continue
        for f in root.rglob("*"):
            if f.suffix not in (".c", ".cpp", ".cc", ".cu", ".h", ".sh"):
                continue
            try:
                text = f.read_text(errors="ignore")
            except OSError:
                continue
            for m in re.finditer(r"\b([a-z][a-z0-9_]{2,})\b", text):
                seen.add(m.group(1))
    return seen

def main():
    lib = library_symbols()
    ref = referenced_symbols()
    if not lib:
        print(f"check-module-coverage: no symbols under {BIN}")
        return 2
    rows = []
    for f in sorted((ROOT / "goose").rglob("*.goose")):
        if "_archive" in f.parts:
            continue
        # staged copies are duplicates of a module that is counted where it lives
        if any("staged" in part for part in f.parts):
            continue
        names = re.findall(r"export fn ([A-Za-z_][A-Za-z0-9_]*)", f.read_text(errors="ignore"))
        if not names:
            continue
        present = [n for n in names if n in lib]
        called = [n for n in present if n in ref]
        rows.append((len(present), len(names), len(called), str(f.relative_to(ROOT))))
    rows.sort(reverse=True)
    wired = sum(1 for p, n, _, _ in rows if p == n)
    partial = sum(1 for p, n, _, _ in rows if 0 < p < n)
    none = sum(1 for p, n, _, _ in rows if p == 0)
    reached = sum(1 for p, n, c, _ in rows if c > 0)
    print(f"{'in lib':>7} {'ref':>7} / exports  module")
    for p, n, c, name in rows[:20]:
        print(f"{p:>7} {c:>7} / {n:<7}  {name}")
    print()
    print(f"modules with all doors in the library: {wired}")
    print(f"modules with some doors:               {partial}")
    print(f"modules with no doors in the library:  {none}")
    print(f"modules with at least one door referenced: {reached}")
    print(f"shipped symbols: {len(lib)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
