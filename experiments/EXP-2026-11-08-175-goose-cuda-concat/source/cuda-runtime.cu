// One GPU thread runs one Goose body invocation, exactly like the native kernel.
// The Goose wrapper keeps the i0 loop and its stride internally; blockIdx,
// gridDim and blockDim are passed in as plain integers.
//
// Contiguous kernel: the native host loops i3 over dst->ne[3] and launches one
// kernel per slice with pointers advanced by nb[3]; the parent reproduces that.
template<int DIM> static __global__ __launch_bounds__(64) void fg175c_cont_kernel(
 const char * a,const char * b,char * d,
 int64_t ne00,int64_t ne01,int64_t ne02,int64_t ne0,int64_t ne1,int64_t ne2,int32_t w){
 if(blockIdx.x==0&&threadIdx.x==0)atomicOr(&fg175c_paths,1ULL<<DIM);
 const uint64_t A=(uint64_t)(uintptr_t)a,B=(uint64_t)(uintptr_t)b,D=(uint64_t)(uintptr_t)d;
 if constexpr(DIM==0){FG175C_CONT0(A,B,D,ne00,ne01,ne02,ne0,ne1,ne2,w,(int32_t)blockIdx.x,(int32_t)threadIdx.x,(int32_t)gridDim.x,(int32_t)blockDim.x,0);}
 else if constexpr(DIM==1){FG175C_CONT1(A,B,D,ne00,ne01,ne02,ne0,ne1,ne2,w,(int32_t)blockIdx.x,(int32_t)threadIdx.x,(int32_t)gridDim.x,(int32_t)blockDim.x,0);}
 else{FG175C_CONT2(A,B,D,ne00,ne01,ne02,ne0,ne1,ne2,w,(int32_t)blockIdx.x,(int32_t)threadIdx.x,(int32_t)gridDim.x,(int32_t)blockDim.x,0);}
}
// Non-contiguous kernel: native grid is exactly (dst.ne1, dst.ne2, dst.ne3), so
// the native i1/i23 blockIdx stride loops each execute exactly once; the Goose
// body therefore uses blockIdx directly and its host plan asserts those bounds.
template<int DIM> static __global__ __launch_bounds__(64) void fg175c_nc_kernel(
 const char * a,const char * b,char * d,
 int64_t ne00,int64_t ne01,int64_t ne02,int64_t ne03,
 int64_t s00,int64_t s01,int64_t s02,int64_t s03,
 int64_t s10,int64_t s11,int64_t s12,int64_t s13,
 int64_t ne0,int64_t d0,int64_t d1,int64_t d2,int64_t d3,int32_t w){
 if(blockIdx.x==0&&threadIdx.x==0&&blockIdx.y==0&&blockIdx.z==0)atomicOr(&fg175c_paths,1ULL<<(4+DIM));
 const uint64_t A=(uint64_t)(uintptr_t)a,B=(uint64_t)(uintptr_t)b,D=(uint64_t)(uintptr_t)d;
 const int64_t bx=(int64_t)blockIdx.x,by=(int64_t)blockIdx.y,bz=(int64_t)blockIdx.z;
 const int64_t tx=(int64_t)threadIdx.x,nt=(int64_t)blockDim.x;
 if constexpr(DIM==0){FG175C_NC0(A,B,D,ne00,ne01,ne02,ne03,s00,s01,s02,s03,s10,s11,s12,s13,ne0,d0,d1,d2,d3,w,bx,by,bz,tx,nt,0);}
 else if constexpr(DIM==1){FG175C_NC1(A,B,D,ne00,ne01,ne02,ne03,s00,s01,s02,s03,s10,s11,s12,s13,ne0,d0,d1,d2,d3,w,bx,by,bz,tx,nt,0);}
 else if constexpr(DIM==2){FG175C_NC2(A,B,D,ne00,ne01,ne02,ne03,s00,s01,s02,s03,s10,s11,s12,s13,ne0,d0,d1,d2,d3,w,bx,by,bz,tx,nt,0);}
 else{FG175C_NC3(A,B,D,ne00,ne01,ne02,ne03,s00,s01,s02,s03,s10,s11,s12,s13,ne0,d0,d1,d2,d3,w,bx,by,bz,tx,nt,0);}
}

struct fg175c_packet{ggml_backend_cuda_context*ctx;ggml_tensor*dst;uint64_t v[8][32]{};bool launched=false;bool memcpy_done=false;};
static std::atomic<uint64_t>fg175c_host_paths{0};
static fg175c_packet&fg175c_p(int64_t p){GGML_ASSERT(p);return*(fg175c_packet*)(uintptr_t)p;}
// `t` is a raw ggml_tensor address handed out by fg175cn_arg; it is not the
// packet. Reading the packet here would be a type confusion, so dereference the
// tensor address directly.
static const ggml_tensor&fg175c_t(int64_t t){GGML_ASSERT(t);return*(const ggml_tensor*)(uintptr_t)t;}

extern "C" int64_t fg175cn_arg(int64_t p,int64_t k){GGML_ASSERT(k==0);return(int64_t)(uintptr_t)fg175c_p(p).dst;}
extern "C" int64_t fg175cn_plan(int64_t p){return p;}
extern "C" void fg175cn_put(int64_t p,int64_t k,int64_t i,uint64_t x){GGML_ASSERT(k>=0&&k<8&&i>=0&&i<32);fg175c_p(p).v[k][i]=x;}
extern "C" uint64_t fg175cn_get(int64_t p,int64_t k,int64_t i){GGML_ASSERT(k>=0&&k<8&&i>=0&&i<32);return fg175c_p(p).v[k][i];}
extern "C" int64_t fg175cn_ti(int64_t p,int64_t k,int64_t i){
 const auto&t=fg175c_t(p);
 switch(k){
  case 0:GGML_ASSERT(i>=0&&i<GGML_MAX_SRC);return(int64_t)(uintptr_t)t.src[i];
  case 1:return(int64_t)(uintptr_t)t.data;
  case 2:return t.type;
  case 3:GGML_ASSERT(i>=0&&i<4);return t.ne[i];
  case 4:GGML_ASSERT(i>=0&&i<4);GGML_ASSERT(t.nb[i]<=INT64_MAX);return(int64_t)t.nb[i];
  case 5:return t.op;
  case 6:return(int64_t)(uintptr_t)t.view_src;
  case 7:GGML_ASSERT(t.view_offs<=INT64_MAX);return(int64_t)t.view_offs;
  case 8:return ggml_get_op_params_i32(&t,(int)i);
  case 9:GGML_ASSERT(ggml_nbytes(&t)<=INT64_MAX);return(int64_t)ggml_nbytes(&t);
  default:GGML_ABORT("CONCAT tensor field");
 }
}
