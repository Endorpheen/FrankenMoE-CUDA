// Launch adapter. Route 0: non-contiguous Goose kernel. Route 1: contiguous
// Goose kernel, one launch per i3 slice. Route 2: the two device-to-device
// memcpy calls the native dim==3 contiguous branch performs (transport only).
extern "C" int64_t fg175cn_launch(int64_t pp){
 auto&p=fg175c_p(pp);GGML_ASSERT(p.ctx);p.launched=true;auto&v=p.v;
 const auto stream=p.ctx->stream();
 const uint64_t route=v[5][0];
 if(route==0){
  const dim3 grid((unsigned)v[4][0],(unsigned)v[4][1],(unsigned)v[4][2]);
  const dim3 block((unsigned)v[4][3]);
  const char*a=(const char*)(uintptr_t)v[1][0+0];GGML_UNUSED(a);
  const char*s0=(const char*)(uintptr_t)v[6][0];
  const char*s1=(const char*)(uintptr_t)v[6][1];
  char*dst=(char*)(uintptr_t)v[6][2];
  auto go=[&](auto kern){ggml_cuda_kernel_launch(kern,ggml_cuda_kernel_launch_params(grid,block,0,stream),s0,s1,dst,
     (int64_t)v[1][0],(int64_t)v[1][1],(int64_t)v[1][2],(int64_t)v[1][3],
     (int64_t)v[1][4],(int64_t)v[1][5],(int64_t)v[1][6],(int64_t)v[1][7],
     (int64_t)v[1][8],(int64_t)v[1][9],(int64_t)v[1][10],(int64_t)v[1][11],
     (int64_t)v[2][0],(int64_t)v[2][4],(int64_t)v[2][5],(int64_t)v[2][6],(int64_t)v[2][7],(int32_t)v[0][0]);};
  switch((int)v[3][0]){case 0:go(fg175c_nc_kernel<0>);break;case 1:go(fg175c_nc_kernel<1>);break;
   case 2:go(fg175c_nc_kernel<2>);break;case 3:go(fg175c_nc_kernel<3>);break;
   default:return cudaErrorInvalidValue;}
  return cudaGetLastError();
 }
 if(route==1){
  const unsigned nt=(unsigned)v[0][2];
  const unsigned gx=(unsigned)v[0][3];
  const int64_t ne3=(int64_t)v[0][4];
  const int64_t ps0=(int64_t)v[0][5],ps1=(int64_t)v[0][6],psd=(int64_t)v[0][7];
  const char*s0=(const char*)(uintptr_t)v[6][0];
  const char*s1=(const char*)(uintptr_t)v[6][1];
  char*dst=(char*)(uintptr_t)v[6][2];
  const int32_t w=(int32_t)v[0][0];
  for(int64_t i3=0;i3<ne3;i3++){
   const dim3 grid(gx,1,1);const dim3 block(nt,1,1);
   const auto lp=ggml_cuda_kernel_launch_params(grid,block,0,stream);
   const char*a=s0+i3*ps0;const char*b=s1+i3*ps1;char*d=dst+i3*psd;
   switch((int)v[2][0]){
    case 0:ggml_cuda_kernel_launch(fg175c_cont_kernel<0>,lp,a,b,d,(int64_t)v[1][0],(int64_t)v[1][1],(int64_t)v[1][2],(int64_t)v[1][3],(int64_t)v[1][4],(int64_t)v[1][5],w);break;
    case 1:ggml_cuda_kernel_launch(fg175c_cont_kernel<1>,lp,a,b,d,(int64_t)v[1][0],(int64_t)v[1][1],(int64_t)v[1][2],(int64_t)v[1][3],(int64_t)v[1][4],(int64_t)v[1][5],w);break;
    case 2:ggml_cuda_kernel_launch(fg175c_cont_kernel<2>,lp,a,b,d,(int64_t)v[1][0],(int64_t)v[1][1],(int64_t)v[1][2],(int64_t)v[1][3],(int64_t)v[1][4],(int64_t)v[1][5],w);break;
    default:return cudaErrorInvalidValue;
   }
  }
  return cudaGetLastError();
 }
 if(route==2){
  const char*s0=(const char*)(uintptr_t)v[6][0];
  const char*s1=(const char*)(uintptr_t)v[6][1];
  char*dst=(char*)(uintptr_t)v[6][2];
  const size_t n0=(size_t)v[7][0],n1=(size_t)v[7][1];
  auto e=cudaMemcpyAsync(dst,s0,n0,cudaMemcpyDeviceToDevice,stream);
  if(e!=cudaSuccess)return e;
  e=cudaMemcpyAsync(dst+n0,s1,n1,cudaMemcpyDeviceToDevice,stream);
  if(e!=cudaSuccess)return e;
  p.memcpy_done=true;
  return cudaGetLastError();
 }
 return cudaErrorInvalidValue;
}

extern "C" uint64_t fg175c_cuda_host_seen(){return fg175c_host_paths.load(std::memory_order_relaxed);}
extern "C" int fg175c_cuda_device_read(uint64_t*out){
 if(!out)return cudaErrorInvalidValue;
 auto e=cudaMemcpyFromSymbol(out,fg175c_paths,sizeof(uint64_t));if(e!=cudaSuccess)return e;
 return cudaMemcpyFromSymbol(out+1,fg175c_invalids,sizeof(uint64_t));
}
static void fg175c_report(){
 uint64_t x[2]={};int e=fg175c_cuda_device_read(x);
 fprintf(stderr,"FG175C_CUDA_CONCAT host=0x%llx,cuda_status=%d,paths=0x%llx,guards=%llu\n",
  (unsigned long long)fg175c_cuda_host_seen(),e,(unsigned long long)x[0],(unsigned long long)x[1]);
}
void fg175c_native_ggml_cuda_op_concat(ggml_backend_cuda_context&,ggml_tensor*);
void ggml_cuda_op_concat(ggml_backend_cuda_context&ctx,ggml_tensor*dst){
 const char*flag=getenv("GGML_GOOSE_CUDA_CONCAT");
 if(flag&&strcmp(flag,"0")==0){fg175c_native_ggml_cuda_op_concat(ctx,dst);return;}
 static std::once_flag once;std::call_once(once,[]{std::atexit(fg175c_report);});
 fg175c_packet p{&ctx,dst};
 p.v[6][0]=(uint64_t)(uintptr_t)(dst->src[0]?dst->src[0]->data:nullptr);
 p.v[6][1]=(uint64_t)(uintptr_t)(dst->src[1]?dst->src[1]->data:nullptr);
 p.v[6][2]=(uint64_t)(uintptr_t)dst->data;
 if(fg175cnh_run((int64_t)(uintptr_t)&p)){
  fg175c_host_paths.fetch_or(p.launched?1ULL<<(8+(p.v[5][0]==0?(int)p.v[3][0]:(int)p.v[2][0])):16ULL,std::memory_order_relaxed);
 }else{
  fg175c_host_paths.fetch_or(32ULL,std::memory_order_relaxed);
  fg175c_native_ggml_cuda_op_concat(ctx,dst);
 }
