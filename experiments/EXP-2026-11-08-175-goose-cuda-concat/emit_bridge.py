from pathlib import Path
import json
F=Path('/home/end0/AI/LlamaServer/franken-goose-exp150-restored-20261108')
E=F/'experiments/EXP-2026-11-08-175-goose-cuda-concat'
S=E/'source'
em=json.loads((E/'emission.json').read_text())
dev=[m for m in em['modules'] if m['module']=='device'][0]
e=dev['entries']
cont=e[0:3]
nc=e[3:7]
assert len(cont)==3 and len(nc)==4,(cont,nc)
lines=['// Generated by emit_bridge.py from emission.json entry order.',
       '// cont wrappers take 14 params, nc wrappers take 26; verified mechanically.']
for i,fn in enumerate(cont):
    lines.append('#define FG175C_CONT%d fg175cd_%s'%(i,fn))
for i,fn in enumerate(nc):
    lines.append('#define FG175C_NC%d fg175cd_%s'%(i,fn))
src=(S/'cuda-runtime.cu').read_text()
hdr='\n'.join(lines)+'\n'
assert '#include "device-functions-generated.cuh"' in src
out=src.replace('#include "device-functions-generated.cuh"',hdr+'#include "device-functions-generated.cuh"')
(S/'cuda-runtime.cu').write_text(out)
(E/'device-abi.json').write_text(json.dumps(dict(
  entries=['fg175cd_'+x for x in e],
  cont_entries=['fg175cd_'+x for x in cont],
  nc_entries=['fg175cd_'+x for x in nc],
  cont_params=14,nc_params=26,
  routes={'0':'concat_non_cont Goose kernel (grid=dst.ne1,ne2,ne3 block=64)',
          '1':'concat_cont Goose kernel, one launch per i3 slice',
          '2':'dim==3 contiguous transport: two cudaMemcpyAsync on the same stream'},
  producer=em['compiler']),indent=2)+'\n')
print('EXP175_BRIDGE_READY',cont,nc)
