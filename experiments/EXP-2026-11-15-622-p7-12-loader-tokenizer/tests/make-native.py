#!/usr/bin/env python3
"""Extract the two oracle bodies out of the native src/llama-vocab.cpp.

The gate does not use a hand transcription. The native text is cut out of the
file the port was written from and wrapped with the smallest set of shims a
header-only harness needs. The shims decide nothing: they echo the case
parameters back and return constants the native body compares against.

  S1  the vocab-type block of llama_vocab::impl::load   -> native-dispatch.{cpp,h}
  S2  llama_vocab::impl::tokenizer_st_partition         -> native-partition.{cpp,h}

Enum names are parsed out of the two native headers, so the canonical record
the gate compares carries native names and no hard-coded numbers.

Usage: make-native.py <llama-vocab.cpp> <llama-vocab.h> <llama.h> <out-dir>
"""
