def cut_dispatch(text):
    start = text.index(DISPATCH_START)
    end = text.index(DISPATCH_END, start)
    body = text[start:end]
    assert body.count('            return;\n') == 1, body.count('            return;\n')
    body = body.replace('            return;\n', '            goto done;\n')
    return body


def cut_partition(text):
    start = text.index(PARTITION_SIG)
    brace = text.index('{', start)
    depth = 0
    for i in range(brace, len(text)):
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return text[brace + 1:i]
    raise SystemExit('unbalanced braces in tokenizer_st_partition')


def names_from(header_text, macro_prefix, pattern):
    pairs = []
    for m in re.finditer(pattern, header_text):
        pairs.append((int(m.group(2)), m.group(1)))
    pairs.sort()
    values = [v for v, _ in pairs]
    if values != list(range(len(values))):
        raise SystemExit(f'{macro_prefix}: non-contiguous enum values')
    return [n for _, n in pairs]


def main():
    src = Path(sys.argv[1])
    precon = Path(sys.argv[2])
    llamah = Path(sys.argv[3])
    out = Path(sys.argv[4])
    text = src.read_text()
    out.mkdir(parents=True, exist_ok=True)

    vtypes = names_from(llamah.read_text(), 'LLAMA_VOCAB_TYPE',
                        r'LLAMA_VOCAB_TYPE_([A-Z0-9_]+)\s*=\s*(\d+)')
    ptypes = names_from(precon.read_text(), 'LLAMA_VOCAB_PRE_TYPE',
                        r'LLAMA_VOCAB_PRE_TYPE_([A-Z0-9_]+)\s*=\s*(\d+)')

    names = ['// Generated by tests/make-native.py from the native headers.',
             'static const char * vocab_type_name(int t) {',
             '    switch (t) {']
    for i, n in enumerate(vtypes):
        names.append(f'        case {i}: return "{n}";')
    names += ['        default: return "?";', '    }', '}', '',
              'static const char * pre_type_name(int p) {',
              '    switch (p) {']
    for i, n in enumerate(ptypes):
        names.append(f'        case {i}: return "{n}";')
    names += ['        default: return "?";', '    }', '}', '']
    names_text = '\n'.join(names)

    body = cut_dispatch(text)
    cpp = CPP_HEAD + body + CPP_TAIL
    cpp = cpp.replace('std::string format_record(',
                      names_text + 'std::string format_record(')
    (out / 'native-dispatch.h').write_text(HEADER)
    (out / 'native-dispatch.cpp').write_text(cpp)

    pbody = cut_partition(text)
    (out / 'native-partition.h').write_text(PARTITION_HEADER)
    (out / 'native-partition.cpp').write_text(
        PARTITION_CPP_HEAD + pbody + PARTITION_CPP_TAIL)

    line0 = text[:text.index(DISPATCH_START)].count('\n') + 1
    print(f'source      {src}')
    print(f'sha256      {hashlib.sha256(text.encode()).hexdigest()}')
    print(f'dispatch    {len(body.splitlines())} native lines from line {line0}')
    print(f'partition   {len(pbody.splitlines())} native lines')
    print(f'enums       {len(vtypes)} vocab types, {len(ptypes)} pre types')


if __name__ == '__main__':
    main()
