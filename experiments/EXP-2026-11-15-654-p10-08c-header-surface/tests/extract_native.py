#!/usr/bin/env python3
"""P10-08 S7-S9 native oracle: re-derive the device-header surface and the
scheduler anchors from the llama.cpp checkout on every build.

Emitted into <outdir>:

  native_devh.inc      DEVH_NUM(name) / DEVH_STR(name) for every macro of the
                       fourteen device backend headers, and DEVH_CHECK(name, id)
                       for every GGML_BACKEND_API declaration.
  native_devh_hdr.inc  DEVH_HDR("name", id): the header each declaration is in.

No value is copied from the port: the fixture expands every macro and classifies
every declaration with decltype against the real headers, so a header that moves
without the port moving fails the gate.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HEADERS = [
    "ggml-cuda.h",
    "ggml-metal.h",
    "ggml-vulkan.h",
    "ggml-rpc.h",
    "ggml-opencl.h",
    "ggml-hexagon.h",
    "ggml-sycl.h",
    "ggml-cann.h",
    "ggml-blas.h",
    "ggml-et.h",
    "ggml-virtgpu.h",
    "ggml-zdnn.h",
    "ggml-zendnn.h",
    "ggml-webgpu.h",
]


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def declarations(text: str) -> list[str]:
    """Every GGML_BACKEND_API declaration, joined across line breaks."""
    flat = re.sub(r"\s+", " ", strip_comments(text))
    out = []
    i = 0
    while True:
        j = flat.find("GGML_BACKEND_API", i)
        if j < 0:
            return out
        k = flat.find(";", j)
        if k < 0:
            raise SystemExit("unterminated declaration in header")
        out.append(flat[j + len("GGML_BACKEND_API"):k].strip())
        i = k + 1


def name_of(decl: str) -> str:
    m = re.match(r"^(.+?)\s*\b([A-Za-z_]\w*)\s*\(", decl)
    if not m:
        raise SystemExit(f"cannot parse declaration: {decl!r}")
    return m.group(2)


def main() -> int:
    if len(sys.argv) < 2:
        print("usage: extract_native.py <llama.cpp root> [outdir]", file=sys.stderr)
        return 2
    root = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("build/native")
    inc = root / "ggml" / "include"
    out.mkdir(parents=True, exist_ok=True)

    consts: list[tuple[str, str]] = []
    const_hdr: list[tuple[str, int]] = []
    funcs: list[tuple[int, str]] = []
    for hid, name in enumerate(HEADERS):
        p = inc / name
        if not p.is_file():
            raise SystemExit(f"missing header: {p}")
        text = p.read_text()
        for line in text.splitlines():
            m = re.match(r"^#define\s+([A-Za-z_]\w*)\s+(.+?)\s*$", line)
            if not m:
                continue
            sym, val = m.group(1), m.group(2)
            if sym.endswith("_H") and val == "":
                continue
            if val.startswith("("):  # function-like macro
                continue
            kind = "str" if val.startswith('"') else "num"
            if kind == "num" and not re.match(r"^[0-9]+$", val):
                continue
            if (sym, hid) not in const_hdr:
                const_hdr.append((sym, hid))
            consts.append((sym, kind))
        for decl in declarations(text):
            funcs.append((hid, name_of(decl)))

    names = [n for _, n in funcs]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise SystemExit(f"duplicate backend declarations: {sorted(dup)}")
    # A macro defined in several #ifdef branches (GGML_CUDA_NAME is "ROCm",
    # "MUSA" or "CUDA") appears more than once; the live expansion is the one the
    # compiler picks, so only the name is kept and the fixture resolves it.
    seen: list[str] = []
    uniq: list[tuple[str, str]] = []
    for sym, kind in consts:
        if sym in seen:
            continue
        seen.append(sym)
        uniq.append((sym, kind))
    consts = uniq
    if len(consts) < 10 or len(funcs) < 60:
        raise SystemExit(f"backend surface shrank: {len(consts)} macros, {len(funcs)} functions")

    lines = ["/* generated by tests/extract_native.py -- do not edit */"]
    for sym, kind in consts:
        lines.append(f'DEVH_{kind.upper()}({sym})')
    for hid, fname in funcs:
        lines.append(f'DEVH_CHECK({fname}, {hid})')
    (out / "native_devh.inc").write_text("\n".join(lines) + "\n")
    hdr = ["/* generated by tests/extract_native.py -- do not edit */"]
    hdr += [f'DEVH_HDR("{fname}", {hid})' for hid, fname in funcs]
    (out / "native_devh_hdr.inc").write_text("\n".join(hdr) + "\n")
    (out / "native_devh_headers.inc").write_text(
        "\n".join(["/* generated by tests/extract_native.py -- do not edit */"]
                  + [f'DEVH_HEADER("{n}")' for n in HEADERS]) + "\n")
    (out / "native_devh_macro.inc").write_text(
        "\n".join(["/* generated by tests/extract_native.py -- do not edit */"]
                  + [f'DEVH_MACRO_HDR("{sym}", {hid})' for sym, hid in const_hdr]) + "\n")

    # ── scheduler eval-callback anchors ────────────────────────────────────
    back = (root / "ggml" / "src" / "ggml-backend.cpp").read_text()
    need_block = back[back.find("if (!sched->callback_eval) {"):]
    end = need_block.find("// record the event of this split")
    if end < 0:
        raise SystemExit("scheduler eval block not found")
    block = need_block[:end]
    anchors = [
        "bool need = sched->callback_eval(t, true, sched->callback_eval_user_data);",
        "while (!need && j1 < split->graph.n_nodes - 1) {",
        "t = split->graph.nodes[++j1];",
        "need = sched->callback_eval(t, true, sched->callback_eval_user_data);",
        "struct ggml_cgraph gv = ggml_graph_view(&split->graph, j0, j1 + 1);",
        "ggml_backend_synchronize(split_backend);",
        "if (need && !sched->callback_eval(t, false, sched->callback_eval_user_data)) {",
        "break;",
        "j0 = j1;",
    ]
    pos = -1
    for a in anchors:
        p = block.find(a, pos + 1)
        if p < 0:
            raise SystemExit(f"scheduler anchor missing or reordered: {a}")
        pos = p
    if block.count("callback_eval(t, true") != 2:
        raise SystemExit("the ask phase is no longer two call sites")
    if block.count("callback_eval(t, false") != 1:
        raise SystemExit("the observe phase is no longer one call site")

    loader = (root / "src" / "llama-model-loader.cpp").read_text()
    prog_anchors = [
        "if (!progress_callback((float) size_done / size_data, progress_callback_user_data)) {",
        "return progress_callback(1.0f, progress_callback_user_data);",
    ]
    ppos = -1
    for a in prog_anchors:
        p = loader.find(a, ppos + 1)
        if p < 0:
            raise SystemExit(f"progress anchor missing: {a}")
        ppos = p
    if loader.count("progress_callback(") < 2:
        raise SystemExit("progress callback lost a call site")

    (out / "native_sched.h").write_text(
        "/* generated by tests/extract_native.py -- do not edit */\n"
        "#pragma once\n"
        f"#define SCHED_ANCHORS {len(anchors)}\n"
        f"#define SCHED_ASK_SITES 2\n"
        f"#define SCHED_OBSERVE_SITES 1\n"
        f"#define PROGRESS_ANCHORS {len(prog_anchors)}\n"
    )

    print(f"devh headers={len(HEADERS)} macros={len(consts)} funcs={len(funcs)}")
    print(f"sched anchors={len(anchors)} progress={len(prog_anchors)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
