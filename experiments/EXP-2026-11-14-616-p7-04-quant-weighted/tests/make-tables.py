#!/usr/bin/env python3
"""Extract the IQ grid/map/neighbour constructors from the native ggml-quants.c.

The IQ row quantizers do not carry their tables as literals: ggml_quantize_init
builds a code->grid map and a neighbour list at start-up. The map and the
neighbour list of the reference are file-static, so a linked fixture cannot read
them. This script copies the two constructor functions (and their helpers) out
of the native file into a generated C translation unit, renaming every symbol
with a tbl_ prefix so it can live next to libggml-base. The gate therefore runs
the port against tables produced by the native construction code, and any
divergence in either the port or the tables shows up as a byte mismatch.

    python3 tests/make-tables.py <native ggml-quants.c> <output.c>

The extracted text is a faithful copy; only identifiers are renamed.
"""
import re
import sys


def find_func(lines, start_pat):
    """Return the text of the function whose definition line matches start_pat."""
    for i, line in enumerate(lines):
        if re.search(start_pat, line) and line.lstrip().startswith(("static", "void", "size_t", "int")):
            depth = 0
            started = False
            out = []
            for j in range(i, len(lines)):
                out.append(lines[j])
                for ch in lines[j]:
                    if ch == "{":
                        depth += 1
                        started = True
                    elif ch == "}":
                        depth -= 1
                if started and depth == 0:
                    return "\n".join(out)
    raise SystemExit("not found: " + start_pat)


RENAME = [
    ("iq2xs_init_impl", "tbl_iq2xs_init"),
    ("iq3xs_init_impl", "tbl_iq3xs_init"),
    ("iq2_data_index", "tbl_iq2_data_index"),
    ("iq2_grid_size", "tbl_iq2_grid_size"),
    ("iq2_compare_func", "tbl_iq2_compare_func"),
    ("iq3_data_index", "tbl_iq3_data_index"),
    ("iq3_compare_func", "tbl_iq3_compare_func"),
    ("iq2_data", "tbl_iq2_data"),
    ("iq3_data", "tbl_iq3_data"),
]


def main():
    native, out = sys.argv[1], sys.argv[2]
    src = open(native, encoding="utf-8").read()
    lines = src.split("\n")

    parts = [
        find_func(lines, r"static inline int iq2_data_index\("),
        find_func(lines, r"static inline int iq2_grid_size\("),
        find_func(lines, r"static int iq2_compare_func\("),
        find_func(lines, r"^void iq2xs_init_impl\("),
        find_func(lines, r"static inline int iq3_data_index\("),
        find_func(lines, r"static int iq3_compare_func\("),
        find_func(lines, r"^void iq3xs_init_impl\("),
    ]
    text = "\n\n".join(parts)
    for old, new in RENAME:
        text = text.replace(old, new)

    header = r"""/* Generated by tests/make-tables.py from the native ggml-quants.c.
   Do not edit; rebuild with tests/build.sh. */
#include <assert.h>
#include <float.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "ggml.h"
#define GGML_COMMON_DECL_C
#include "ggml-common.h"

#define NGRID_IQ1S 2048

typedef struct { uint64_t * grid; int * map; uint16_t * neighbours; } iq2_entry_t;
static iq2_entry_t tbl_iq2_data[4] = { {NULL,NULL,NULL}, {NULL,NULL,NULL}, {NULL,NULL,NULL}, {NULL,NULL,NULL} };

typedef struct { uint32_t * grid; int * map; uint16_t * neighbours; } iq3_entry_t;
static iq3_entry_t tbl_iq3_data[2] = { {NULL,NULL,NULL}, {NULL,NULL,NULL} };

"""
    footer = r"""

/* Accessors used by tests/fixture.cpp. The grid code of an iq2 entry is eight
   signed bytes; an iq3 entry is four. They are returned as an integer so the
   port can mask them itself. */
void tbl_init_iq2(int type) { tbl_iq2xs_init((enum ggml_type) type); }
void tbl_init_iq3(int grid_size) { tbl_iq3xs_init(grid_size); }
uint64_t tbl_iq2_grid(int g, int i) { return tbl_iq2_data[g].grid[i]; }
int tbl_iq2_map(int g, int u) { return tbl_iq2_data[g].map[u]; }
int tbl_iq2_nb(int g, int off) { return tbl_iq2_data[g].neighbours[off]; }
uint64_t tbl_iq3_grid(int g, int i) { return tbl_iq3_data[g].grid[i]; }
int tbl_iq3_map(int g, int u) { return tbl_iq3_data[g].map[u]; }
int tbl_iq3_nb(int g, int off) { return tbl_iq3_data[g].neighbours[off]; }
void tbl_free(void) {
    for (int i = 0; i < 4; ++i) { free(tbl_iq2_data[i].grid); free(tbl_iq2_data[i].map); free(tbl_iq2_data[i].neighbours); }
    for (int i = 0; i < 2; ++i) { free(tbl_iq3_data[i].grid); free(tbl_iq3_data[i].map); free(tbl_iq3_data[i].neighbours); }
}
"""
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + text + footer)
    print("wrote", out, len(text.split("\n")), "extracted lines")


if __name__ == "__main__":
    main()
