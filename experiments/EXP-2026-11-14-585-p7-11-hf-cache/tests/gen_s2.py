def tsv():
    rows = ["# EXP585 S2 case table (tests/gen_s2.py); the oracle is build/native_s2.out",
            "# fields: case|kind|..."]
    for i, v in enumerate(REPO):
        rows.append("R%d|repo|%s" % (i, v))
    for i, v in enumerate(FOLD):
        rows.append("G%d|fold|%s" % (i, v))
    for i, v in enumerate(TOKEN):
        rows.append("T%d|token|%s" % (i, v))
    for i, v in enumerate(COMMIT):
        rows.append("C%d|commit|%s" % (i, v))
    for i, v in enumerate(SUBPATH):
        rows.append("S%d|subpath|%s" % (i, v))
    for i, c in enumerate(PATHS):
        rows.append("P%d|paths|%s|%s|%s|%s|%d" % ((i,) + c))
    for i, table in enumerate(REFS):
        rows.append("F%d|refs|%s" % (i, ";".join("%s=%s:%d" % e for e in table)))
    for i, c in enumerate(FINALIZE):
        rows.append("Z%d|finalize|%d|%d|%d" % ((i,) + c))
    return "\n".join(rows) + "\n"


