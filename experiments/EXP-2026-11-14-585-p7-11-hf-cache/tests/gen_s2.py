def cpp_str(s):
    out = []
    for b in s.encode():
        if 32 <= b < 127 and chr(b) not in '"\\':
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


def go_str(s):
    out = []
    for b in s.encode():
        if b == 34:
            out.append('\\"')
        elif b == 92:
            out.append("\\\\")
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


