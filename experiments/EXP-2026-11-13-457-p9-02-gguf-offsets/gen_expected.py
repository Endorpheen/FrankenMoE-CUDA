#!/usr/bin/env python3
"""Derive the GGUF tensor layout from the Apex file, independently of Goose.

The script parses the container structure with struct (header, metadata, tensor
descriptors), reads the type size/block table from the gguf library and computes
padded offsets. It then cross-checks the result against the library's own
per-tensor absolute offsets (GGUFReader.data_offset), so two independent
implementations must agree before the Goose gate runs.
"""
import struct
import sys
from pathlib import Path

import gguf

F = Path('/home/end0/AI/LlamaServer/franken-goose-exp150-restored-20261108')
E = F / 'experiments/EXP-2026-11-13-457-p9-02-gguf-offsets'
MODEL = Path('/home/end0/AI/LocalAI/Models/Apex-35B-V0.0-Q4_K_M.gguf')
MODEL = Path('/home/end0/AI/LocalAI/Models/Apex-35B-V1.0-Q4_K_M.gguf')

TYPE_TABLE = {int(k.value): v for k, v in gguf.GGML_QUANT_SIZES.items()}
DEFAULT_ALIGNMENT = 32
ALIGN_KEY = b'general.alignment'


class R:
    def __init__(self, data):
        self.d = data
        self.p = 0

    def u32(self):
        v = struct.unpack_from('<I', self.d, self.p)[0]
        self.p += 4
        return v

    def u64(self):
        v = struct.unpack_from('<Q', self.d, self.p)[0]
        self.p += 8
        return v

    def take(self, n):
        if self.p + n > len(self.d):
            raise ValueError('eof')
        v = self.d[self.p:self.p + n]
        self.p += n
        return v

    def string(self):
        n = self.u64()
        return self.take(n)


def skip(r, t):
    if t in (0, 1, 7):
        r.take(1)
    elif t in (2, 3):
        r.take(2)
    elif t in (4, 5, 6):
        r.take(4)
    elif t in (10, 11, 12):
        r.take(8)
    elif t == 8:
        r.string()
    else:
        raise ValueError(f'type {t}')


def pad(x, n):
    return (x + n - 1) & ~(n - 1)


def main():
    data = MODEL.read_bytes()
    r = R(data)
    magic = r.u32()
    if magic != int.from_bytes(b'GGUF', 'little'):
        print('bad magic')
        return 1
    version = r.u32()
    if version not in (2, 3):
        print('bad version', version)
        return 1
    n_tensors = r.u64()
    n_kv = r.u64()

    alignment = DEFAULT_ALIGNMENT
    for _ in range(n_kv):
        key = r.string()
        vt = r.u32()
        if vt == 9:
            et = r.u32()
            cnt = r.u64()
            if key == ALIGN_KEY:
                if et != 4 or cnt != 1:
                    print('unexpected alignment array shape')
                    return 1
                alignment = struct.unpack_from('<I', data, r.p)[0]
            for _ in range(cnt):
                skip(r, et)
        else:
            if key == ALIGN_KEY:
                if vt != 4:
                    print('unexpected alignment type')
                    return 1
                alignment = struct.unpack_from('<I', data, r.p)[0]
            skip(r, vt)

    if alignment <= 0 or (alignment & (alignment - 1)) != 0:
        print('alignment is not a power of two:', alignment)
        return 1

    descriptors = []
    for _ in range(n_tensors):
        name = r.string()
        nd = r.u32()
        if nd < 1 or nd > 4:
            print('bad ndims')
            return 1
        dims = [r.u64() for _ in range(nd)]
        ttype = r.u32()
        off = r.u64()
        descriptors.append((name, dims, ttype, off))

    structural_end = r.p
    data_start = pad(structural_end, alignment)

    # independent cross-check: the library's own absolute offsets
    reader = gguf.GGUFReader(str(MODEL))
    if len(reader.tensors) != n_tensors:
        print('tensor count mismatch', len(reader.tensors), n_tensors)
        return 1

    running = 0
    rows = []
    for i, (name, dims, ttype, off) in enumerate(descriptors):
        if ttype not in TYPE_TABLE:
            print('unknown type', ttype)
            return 1
        blk, tsize = TYPE_TABLE[ttype]
        ne = 1
        for d in dims:
            ne *= d
        if ne % blk:
            print('nelements not divisible', name, ne, blk)
            return 1
        nb = tsize * (ne // blk)
        if off != running:
            print('non-cumulative offset', name, off, running)
            return 1
        abs_off = data_start + off
        lib = int(reader.tensors[i].data_offset)
        if lib != abs_off:
            print('library disagrees', name, lib, abs_off)
            return 1
        if reader.tensors[i].name != name.decode():
            print('name order mismatch', reader.tensors[i].name, name)
            return 1
        rows.append((off, nb, abs_off))
        running += pad(nb, alignment)

    inc = [
        '// generated by gen_expected.py from the Apex GGUF',
        f'#define EXP457_ALIGN {alignment}',
        f'#define EXP457_DATA_START {data_start}',
        f'#define EXP457_STRUCTURAL_END {structural_end}',
        f'#define EXP457_N {len(rows)}',
        f'#define EXP457_TOTAL {running}',
        'static const int64_t REL_OFFSETS[] = {',
        '  ' + ', '.join(str(a) for a, _, _ in rows),
        '};',
        'static const int64_t NBYTES[] = {',
        '  ' + ', '.join(str(b) for _, b, _ in rows),
        '};',
        'static const int64_t ABS_OFFSETS[] = {',
        '  ' + ', '.join(str(c) for _, _, c in rows),
        '};',
    ]
    (E / 'tests').mkdir(parents=True, exist_ok=True)
    (E / 'tests/expected_layout.inc').write_text('\n'.join(inc) + '\n')
    print(f'FG457_EXPECTED tensors={len(rows)} alignment={alignment} '
          f'structural_end={structural_end} data_start={data_start} total={running}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
