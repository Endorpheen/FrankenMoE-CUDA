#!/usr/bin/env python3
"""Audit the per-endpoint required-field contract against the native source.

The table below is the contract that EXP451 ports to Goose. Every entry cites
the native line that justifies it; this script re-reads those lines so a stale
table fails the build. It also emits the fixture's expected table, so the gate
compares Goose with the audited source rather than with a second hand copy.
"""
import sys
from pathlib import Path

SERVER = Path('/home/end0/AI/LlamaServer/llama.cpp-flint-cuda/tools/server')
F = Path('/home/end0/AI/LlamaServer/franken-goose-exp150-restored-20261108')
E = F / 'experiments/EXP-2026-11-13-451-p8-02-required-fields'

F_PROMPT = 1
F_MESSAGES = 2
F_INPUT = 4
F_INPUT_PREFIX = 8
F_INPUT_SUFFIX = 16
F_CONTENT = 32
F_QUERY = 64
F_DOCUMENTS = 128
F_MODEL = 256
F_CONTROL_ID = 512
F_ARRAY_BODY = 1024
F_FILE = 2048

# category: (bits, [(file, line, expected substring), ...])
TABLE = {
    6:  (F_MODEL,        [('server-models.cpp', 2594, 'model must be a non-empty string')]),
    11: (F_PROMPT,       [('server-context.cpp', 5192, 'data.at("prompt")')]),
    12: (F_PROMPT,       [('server-common.cpp', 1159, 'prompt')]),
    13: (F_MESSAGES,     [('server-common.cpp', 1402, 'messages')]),
    14: (F_CONTROL_ID,   [('server-context.cpp', 5890, 'missing completion id')]),
    15: (F_INPUT,        [('server-chat.cpp', 8, "input")]),
    16: (F_FILE,         [('server-chat.cpp', 670, 'No input file found')]),
    19: (F_MESSAGES,     [('server-chat.cpp', 377, 'contains("messages")')]),
    20: (F_INPUT_PREFIX | F_INPUT_SUFFIX,
                         [('server-context.cpp', 5783, 'input_prefix'),
                          ('server-context.cpp', 5787, 'input_suffix')]),
    21: (F_INPUT | F_CONTENT,
                         [('server-context.cpp', 6802, 'must be provided')]),
    22: (F_INPUT | F_CONTENT,
                         [('server-context.cpp', 6802, 'must be provided')]),
    23: (F_QUERY | F_DOCUMENTS,
                         [('server-context.cpp', 6308, 'query'),
                          ('server-context.cpp', 6315, 'documents')]),
    27: (F_MESSAGES,     [('server-common.cpp', 1402, 'messages')]),
    28: (F_MESSAGES,     [('server-common.cpp', 1402, 'messages')]),
    29: (F_INPUT,        [('server-chat.cpp', 8, "input")]),
    30: (F_MESSAGES,     [('server-chat.cpp', 377, 'contains("messages")')]),
    32: (F_ARRAY_BODY,   [('server-context.cpp', 6649, 'must be an array')]),
}


def main():
    cache = {}
    checked = 0
    for cat, (bits, cites) in sorted(TABLE.items()):
        for fn, line, want in cites:
            if fn not in cache:
                cache[fn] = (SERVER / fn).read_text().splitlines()
            text = cache[fn][line - 1]
            if want not in text:
                print(f'CITATION DRIFT cat={cat} {fn}:{line} missing {want!r}')
                print(f'  line: {text.strip()}')
                return 1
            checked += 1

    inc = ['// generated by audit.py from the native handlers']
    for cat, (bits, cites) in sorted(TABLE.items()):
        why = ' | '.join(f'{fn}:{line}' for fn, line, _ in cites)
        inc.append(f'{{ {cat}, {bits}, "{why}" }},')
    (E / 'tests').mkdir(parents=True, exist_ok=True)
    (E / 'tests/expected_required.inc').write_text('\n'.join(inc) + '\n')
    print(f'FG451_AUDIT categories={len(TABLE)} citations={checked} ok')
    return 0


if __name__ == '__main__':
    sys.exit(main())
