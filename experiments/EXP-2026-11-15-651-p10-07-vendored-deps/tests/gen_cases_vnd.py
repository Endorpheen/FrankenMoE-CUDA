#!/usr/bin/env python3
"""Regenerate tests/cases/vnd.tsv from the native material.

The table is a build input, not a hand-written list: it names every URL in
tests/native/sync_vendor.py, every patch anchor of every patched file (both the
upstream arm and the checked-in arm), the tree facts of every file under the
vendor directory, and a synthetic boundary set for each decision.

    python3 tests/gen_cases_vnd.py <sync_vendor.py> <vendor-root> <out.tsv>
"""
import ast
import re
import sys
from pathlib import Path

NATIVE = Path(sys.argv[1]).resolve()
ROOT = Path(sys.argv[2]).resolve()
OUT = Path(sys.argv[3]).resolve()

SRC = NATIVE.read_text()
CONST = dict(re.findall(r'(?m)^([A-Z][A-Z0-9_]*)\s*=\s*"([^"]*)"\s*$', SRC))
block = re.search(r"(?ms)^vendor\s*=\s*\{(.*?)^\}", SRC)
VENDOR = {}
for raw_line in block.group(1).splitlines():
    line = raw_line.split("#")[0].strip()
    m = re.match(r'^([fr]?)"([^"]*)"\s*:\s*"([^"]*)"\s*,\s*$', line)
    if not m:
        continue
    prefix, url, path = m.groups()
    VENDOR[url.format(**CONST) if prefix == "f" else url] = path

PATCHES = None
for n in ast.parse(SRC).body:
    if isinstance(n, ast.Assign) and any(getattr(t, "id", "") == "patches" for t in n.targets):
        PATCHES = ast.literal_eval(n.value)
if PATCHES is None:
    sys.exit("gen: patch table not found")


def esc(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace("\t", "\\t")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )


rows = []
rows.append("# generated by tests/gen_cases_vnd.py — do not edit by hand")

# every URL in the real table, in table order
for url in VENDOR:
    rows.append(f"pin\t{esc(url)}")
    rows.append(f"pin_name\t{esc(url)}")

# synthetic pin shapes: what a careless table entry would look like
SYNTH = [
    "https://raw.githubusercontent.com/o/r/refs/tags/v1.2.3/f.h",
    "https://raw.githubusercontent.com/o/r/refs/tags/v1.2.3+build.5/f.h",
    "https://raw.githubusercontent.com/o/r/0123456789abcdef0123456789abcdef01234567/f.h",
    "https://raw.githubusercontent.com/o/r/0123456789ABCDEF0123456789ABCDEF01234567/f.h",
    "https://raw.githubusercontent.com/o/r/0123456789abcdef0123456789abcdef0123456/f.h",
    "https://raw.githubusercontent.com/o/r/0123456789abcdef0123456789abcdef012345678/f.h",
    "https://raw.githubusercontent.com/o/r/refs/heads/main/f.h",
    "https://raw.githubusercontent.com/o/r/master/f.h",
    "https://raw.githubusercontent.com/o/r/refs/pull/123/head/f.h",
    "https://github.com/o/r/releases/latest/download/f.h",
    "https://github.com/o/r/archive/refs/tags/v2.0.0.tar.gz",
    "https://example.com/f.h",
    "",
]
for url in SYNTH:
    rows.append(f"pin\t{esc(url)}")
    rows.append(f"pin_name\t{esc(url)}")

# reproducibility of each class, including out-of-range kinds
for k in ["0", "1", "2", "3", "4", "5", "-1", "99"]:
    rows.append(f"repro\t{k}")

# patch anchors: the real table, both arms
for rel, anchors in PATCHES.items():
    name = Path(rel).name
    for idx in range(len(anchors)):
        # the checked-in file is the patched one, so this measures the real
        # answer to "does the anchor still occur exactly once here"; the
        # upstream arm needs the reverse substitution and is out of scope for a
        # file the gate cannot rebuild
        rows.append(f"real_anchor\t{rel}\t{idx}\t{esc(anchors[idx][0])}")
        rows.append(f"anchor\t{name}\t{esc(anchors[idx][0])}")

# synthetic counting: empty anchor, two hits, overlapping hits, at the edges
rows += [
    "anchor\tdelim.txt\t~512~",
    "anchor\tdelim.txt\tt",
    "anchor\tdelim.txt\t))",
    "anchor_state\t0",
    "anchor_state\t1",
    "anchor_state\t2",
    "anchor_state\t72",
]

# patch bytes, synthetic
rows += [
    "patch\taXbXc\tX\tY",
    "patch\taXc\tX\tY",
    "patch\taaa\taa\tb",
    "patch\t\ta\tb",
    "patch\ta\t\tQ",
    "patch\theader\\nbody\\n\tbody\tbody2",
    "patch\tnone\tabc\tx",
]

# the real tree: one row per file the table names plus one per file present
files = set()
for rel in VENDOR.values():
    files.add(rel)
for p in sorted(ROOT.rglob("*")):
    if p.is_file():
        # paths in the table are relative to the llama.cpp root, as sync_vendor.py
        # writes them ("vendor/nlohmann/json.hpp")
        files.add(p.relative_to(ROOT.parent).as_posix())
GENERATED = {"vendor/cpp-httplib/httplib.h", "vendor/cpp-httplib/httplib.cpp"}


def pin_of(rel):
    url = next((u for u, v in VENDOR.items() if v == rel), None)
    if url is None:
        return 0
    if "releases/latest/download" in url:
        return 4
    if "/refs/heads/" in url:
        return 3
    if "/refs/tags/" in url:
        return 1
    if re.search(r"(?<=/)[0-9a-fA-F]{40}(?=/|$)", url):
        return 2
    return 0


for rel in sorted(files):
    declared = 1 if rel in VENDOR.values() else 0
    present = 1 if (ROOT.parent / rel).is_file() else 0
    url = next((u for u, v in VENDOR.items() if v == rel), None)
    reproducible = 1 if url and pin_of(rel) in (1, 2) else 0
    owned = 1 if (rel in GENERATED or Path(rel).name == "CMakeLists.txt") else 0
    rows.append(f"tree_state\t{rel}\t{declared}\t{present}\t{reproducible}\t{owned}")

# synthetic state precedence: all 16 combinations of the four booleans
for m in range(16):
    declared, present, reproducible, owned = (m >> 3) & 1, (m >> 2) & 1, (m >> 1) & 1, m & 1
    rows.append(f"tree_state_synth\t{declared}\t{present}\t{reproducible}\t{owned}")

OUT.write_text("\n".join(rows) + "\n")
print(f"{len(rows)} rows -> {OUT}")
