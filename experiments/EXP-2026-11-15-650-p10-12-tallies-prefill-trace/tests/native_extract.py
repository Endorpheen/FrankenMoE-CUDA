#!/usr/bin/env python3
"""Extract the native regions of the four P10-12 slices, verbatim.

The differential gates do not retype the native code: they compile the exact
text of the base-commit translation units. session.cpp and cli/main.cpp cannot
be linked whole (they pull llama.cpp, the hooks and the sinks), and several of
the regions live in anonymous namespaces or inside `generate()`, so the gate
build copies the byte ranges out of the real files and `#include`s them.

Every anchor is an exact line prefix. A missing or ambiguous anchor is an
error, so a rebase that moves the code is noticed rather than silently
producing an empty oracle.

    python3 tests/native_extract.py <repo> <out-dir>
"""

import os
import sys

SESSION = "runtime/core/src/engine/session.cpp"
CLI = "runtime/cli/main.cpp"


def strip_code(line):
    """Blank out comments and literals so brace counting cannot be fooled."""
    out = []
    i = 0
    n = len(line)
    state = None  # None, 'line', 'block', 'str', 'chr'
    while i < n:
        c = line[i]
        two = line[i:i + 2]
        if state is None:
            if two == "//":
                break
            if two == "/*":
                state = "block"
                out.append("  ")
                i += 2
                continue
            if c == '"':
                state = "str"
                out.append(" ")
            elif c == "'":
                state = "chr"
                out.append(" ")
            else:
                out.append(c)
        elif state == "block":
            if two == "*/":
                state = None
                out.append("  ")
                i += 2
                continue
            out.append(" ")
        elif state in ("str", "chr"):
            if c == "\\":
                out.append("  ")
                i += 2
                continue
            if (state == "str" and c == '"') or (state == "chr" and c == "'"):
                state = None
            out.append(" ")
        i += 1
    return "".join(out)


def read_lines(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read().split("\n")


def find_unique(lines, anchor, where):
    hits = [i for i, line in enumerate(lines) if line.startswith(anchor)]
    if len(hits) != 1:
        raise SystemExit("%s: anchor %r matched %d lines, expected 1" % (where, anchor, len(hits)))
    return hits[0]


def take_block(lines, start, where, anchor):
    """From `start` to the line that closes the outermost brace, inclusive."""
    depth = 0
    seen = False
    for i in range(start, len(lines)):
        code = strip_code(lines[i])
        for c in code:
            if c == "{":
                depth += 1
                seen = True
            elif c == "}":
                depth -= 1
        if seen and depth == 0:
            return lines[start:i + 1]
    raise SystemExit("%s: block %r is not closed" % (where, anchor))


def take_n(lines, start, n, where, anchor):
    block = lines[start:start + n]
    if len(block) != n:
        raise SystemExit("%s: anchor %r needs %d lines" % (where, anchor, n))
    return block


def emit(out_dir, name, header_comment, body):
    path = os.path.join(out_dir, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tests/native_extract.py from %s — verbatim native text.\n" % header_comment)
        f.write("\n".join(body))
        f.write("\n")
    return path


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: native_extract.py <repo> <out-dir>")
    repo, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    sess = read_lines(os.path.join(repo, SESSION))
    cli = read_lines(os.path.join(repo, CLI))
    made = []

    a = "struct GenTally {"
    made.append(emit(out_dir, "native_gen_tally.h", SESSION + " " + a,
                     take_block(sess, find_unique(sess, a, SESSION), SESSION, a)))
    a = "struct PrefillTally {"
    made.append(emit(out_dir, "native_prefill_tally.h", SESSION + " " + a,
                     take_block(sess, find_unique(sess, a, SESSION), SESSION, a)))

    a = "    for (int i = (int) n_common; i < n_prompt; i += im.cfg.n_batch) {"
    made.append(emit(out_dir, "native_prefill_loop.inc", SESSION + " prefill chunk loop",
                     take_n(sess, find_unique(sess, a, SESSION), 2, SESSION, a)))

    a = "    auto trace_begin = [&](int base_pos, int n_tokens, int phase) {"
    made.append(emit(out_dir, "native_trace_begin.inc", SESSION + " trace_begin",
                     take_block(sess, find_unique(sess, a, SESSION), SESSION, a)))
    a = "    auto trace_flush = [&]() {"
    made.append(emit(out_dir, "native_trace_flush.inc", SESSION + " trace_flush",
                     take_block(sess, find_unique(sess, a, SESSION), SESSION, a)))

    a = "static void print_predict_report(const RunSummary & s) {"
    made.append(emit(out_dir, "native_predict_report.inc", CLI + " print_predict_report",
                     take_block(cli, find_unique(cli, a, CLI), CLI, a)))

    a = "    s.majflt_per_token ="
    made.append(emit(out_dir, "native_summary_a.inc", SESSION + " summary per-token averages",
                     take_n(sess, find_unique(sess, a, SESSION), 2, SESSION, a)))
    a = "        s.moe_read_mib ="
    made.append(emit(out_dir, "native_summary_b.inc", SESSION + " summary moe averages",
                     take_n(sess, find_unique(sess, a, SESSION), 8, SESSION, a)))
    a = "        s.moe_drain_s_per_token ="
    made.append(emit(out_dir, "native_summary_c.inc", SESSION + " summary drain/adopt averages",
                     take_n(sess, find_unique(sess, a, SESSION), 2, SESSION, a)))

    for p in made:
        print(p)


if __name__ == "__main__":
    main()
