#!/usr/bin/env python3
"""Extract the native regions of the three P9-08 G4/G5/G7 slices, verbatim.

The differential gates do not retype the native code: they compile the exact
text of the base-commit translation units. session.cpp and cli/main.cpp cannot
be linked whole (session.cpp pulls llama.cpp, the router hook and three trace
sinks; main.cpp pulls the engine), so the gate build copies the byte ranges out
of the real files and `#include`s them inside fixture functions that supply the
services the port deliberately does not own.

Every anchor is an exact line prefix and must match exactly one line, so a
rebase that moves a region is noticed instead of silently producing an empty
oracle.

    python3 tests/native_extract.py <repo> <out-dir>
"""

import os
import sys

SESSION = "runtime/core/src/engine/session.cpp"
CLI = "runtime/cli/main.cpp"


def read_lines(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read().split("\n")


def find_unique(lines, anchor, where):
    hits = [i for i, line in enumerate(lines) if line.startswith(anchor)]
    if len(hits) != 1:
        raise SystemExit("%s: anchor %r matched %d lines, expected 1" % (where, anchor, len(hits)))
    return hits[0]


def take_range(lines, start_anchor, end_anchor, where):
    a = find_unique(lines, start_anchor, where)
    b = find_unique(lines, end_anchor, where)
    if b < a:
        raise SystemExit("%s: end anchor %r precedes start %r" % (where, end_anchor, start_anchor))
    return lines[a:b + 1]


def take_until(lines, start_anchor, stop_anchor, where):
    """From the start anchor up to (not including) the stop anchor's line."""
    a = find_unique(lines, start_anchor, where)
    b = find_unique(lines, stop_anchor, where)
    if b <= a:
        raise SystemExit("%s: stop anchor %r does not follow start %r" % (where, stop_anchor, start_anchor))
    return lines[a:b]


def take_n(lines, anchor, n, where, last_exact=None):
    a = find_unique(lines, anchor, where)
    block = lines[a:a + n]
    if len(block) != n:
        raise SystemExit("%s: anchor %r needs %d lines, file ends first" % (where, anchor, n))
    if last_exact is not None and block[-1] != last_exact:
        raise SystemExit("%s: anchor %r does not end with %r (got %r)"
                         % (where, anchor, last_exact, block[-1]))
    return block


def emit(out_dir, name, header_comment, body):
    path = os.path.join(out_dir, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tests/native_extract.py from %s - verbatim native text.\n" % header_comment)
        f.write("\n".join(body))
        f.write("\n")
    return path


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: native_extract.py <repo> <out-dir>")
    repo, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    sess = read_lines(os.path.join(repo, SESSION))
    cli = read_lines(os.path.join(repo, CLI))
    made = []

    # ── G5: the sampler chain (session.cpp:937-945) ─────────────────────────
    a = "    static_assert(SamplingConfig{}.seed == LLAMA_DEFAULT_SEED,"
    made.append(emit(out_dir, "native_sampler_chain.inc", SESSION + " sampler chain",
                     take_n(sess, a, 9, SESSION, last_exact="    }")))

    # ── G4: the capture warm-up (session.cpp:992-1008) ──────────────────────
    made.append(emit(out_dir, "native_warm_seq.inc", SESSION + " capture warm-up",
                     take_range(sess, "        im.hook->begin_capture();",
                                "        im.hook->end_capture();", SESSION)))

    # ── G4: the harvest (session.cpp:1011-1037) ─────────────────────────────
    made.append(emit(out_dir, "native_warm_walk.inc", SESSION + " captured-layer harvest",
                     take_range(sess, "        const GgufOffsets & offs = meta().offsets;",
                                '        if (n_bound == 0) return fail("no MoE expert tensors captured',
                                SESSION)))

    # ── G4: the KV wipe after the warm-up (session.cpp:1129-1130) ───────────
    made.append(emit(out_dir, "native_warm_clear.inc", SESSION + " warm-up KV wipe",
                     take_n(sess, "        llama_memory_clear(llama_get_memory(ctx), true); // discard warm-up KV",
                            2, SESSION,
                            last_exact="        if (im.ctx_dft) llama_memory_clear(llama_get_memory(im.ctx_dft.get()), true);")))

    # ── G4: the dense/row split (session.cpp:1056-1080) ─────────────────────
    made.append(emit(out_dir, "native_dense_filter.inc", SESSION + " dense/row split",
                     take_until(sess, "            for (const auto & kv : im.hook->captured_weights()) {",
                                "            const uint64_t row_budget =", SESSION)))

    # ── G4: the row window (session.cpp:1082) ───────────────────────────────
    made.append(emit(out_dir, "native_row_budget.inc", SESSION + " row-stream window",
                     take_n(sess, "            const uint64_t row_budget =", 1, SESSION)))

    # ── G7: the argument parse loop (cli/main.cpp:606-776) ──────────────────
    made.append(emit(out_dir, "native_parse_loop.inc", CLI + " argument parse loop",
                     take_until(cli, "    for (int i = 1; i < argc; ++i) {",
                                "    // Env overrides (flag wins", CLI)))

    # ── G7: the workload/mode rejection (cli/main.cpp:876-883) ──────────────
    made.append(emit(out_dir, "native_workload_gate.inc", CLI + " workload/mode rejection",
                     take_until(cli, "    if (!cfg.workload_capture_path.empty() || !cfg.workload_replay_path.empty()) {",
                                "    if (session_mode) return run_session_loop(", CLI)))

    # ── G7: the --ppl-list open refusal (cli/main.cpp:887-891) ──────────────
    made.append(emit(out_dir, "native_ppl_list_open.inc", CLI + " --ppl-list open refusal",
                     take_until(cli, "            std::ifstream lf(ppl_list);",
                                "            std::string line;", CLI)))

    # ── G7: the --ppl file open refusal (cli/main.cpp:910-914) ──────────────
    made.append(emit(out_dir, "native_ppl_file_open.inc", CLI + " --ppl file open refusal",
                     take_until(cli, "            std::ifstream tf(path, std::ios::binary);",
                                "            std::ostringstream ts;", CLI)))

    # ── G7: the --ppl-list line filter (cli/main.cpp:893-895) ───────────────
    a = "                while (!line.empty() && (line.back() == '\\r' || line.back() == ' '))"
    made.append(emit(out_dir, "native_list_filter.inc", CLI + " --ppl-list line filter",
                     take_n(cli, a, 3, CLI)))

    # ── G7: the two mode conditions (cli/main.cpp:880, 885) ─────────────────
    made.append(emit(out_dir, "native_mode.inc", CLI + " mode dispatch conditions",
                     [read_lines(os.path.join(repo, CLI))[find_unique(cli, "    if (session_mode) return run_session_loop(", CLI)],
                      read_lines(os.path.join(repo, CLI))[find_unique(cli, "    if (!ppl_path.empty() || !ppl_list.empty()) {", CLI)]]))

    for p in made:
        print(p)


if __name__ == "__main__":
    main()
