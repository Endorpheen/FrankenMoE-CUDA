#!/usr/bin/env python3
"""W1 gate: the artifact policy in tools/check-generated-files.py.

Arm A (corpus, 23 rows): the accepted P10-05 S3 case table, evaluated twice —
through the host (`GEN`, `LIM`, `GATE`) and by the script's own inline branch —
which is exactly what BMOE_GOOSE_ART flips. A difference is a wiring defect.

Arm B (end to end, 14 staged trees): a scratch git repository, the real hook
script, both modes, comparing exit code, stdout and stderr byte for byte.

Usage: w1_art.py
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from host import CORPUS, ROOT, Host, cases, decode, field, hx, Tally  # noqa: E402

SCRIPT = ROOT / "tools" / "check-generated-files.py"
GENERATED_HEAD = (b"/* Generated by the Goose compiler from a.goose. Do not edit.\n"
                  b"/* ==== runtime.h ==== */\nint x;\n")


def load_script():
    spec = importlib.util.spec_from_file_location("check_generated", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def decode_head(raw: str) -> bytes:
    """`~512~` is 512 filler bytes; backslash escapes are decoded."""
    out = b""
    if "~512~" in raw:
        before, after = raw.split("~512~", 1)
        out += decode(before).encode() + b"x" * 512 + decode(after).encode()
        return out
    return decode(raw).encode()


def arm_corpus(mod, host) -> Tally:
    t = Tally("FG663_ART_CORPUS")
    rows = cases(CORPUS / "cases" / "art.tsv")
    wired = {"generated", "limit", "gate"}
    for i, row in enumerate(rows, 1):
        kind = row[0]
        if kind not in wired:
            # required/required_parts/manifest/verdict/exports belong to
            # tools/check-goose-tree.py, which this wiring does not touch.
            continue
        t.rows += 1
        if kind == "generated":
            path, head = field(row, 1), decode_head(field(row, 2))
            t.eq(i, kind, mod.is_generated_goose_c(path, head, None),
                 mod.is_generated_goose_c(path, head, host))
        elif kind == "limit":
            mb_milli = int(field(row, 1))
            # The script takes MiB from the CLI, the slice milli-MiB.
            mb = mb_milli / 1000
            t.eq(i, kind, mod.size_limit(mb, None), mod.size_limit(mb, host))
        elif kind == "gate":
            all_flag, size, limit = int(field(row, 1)), int(field(row, 2)), int(field(row, 3))
            t.eq(i, kind, mod.gate(bool(all_flag), size, limit, None),
                 mod.gate(bool(all_flag), size, limit, host))
    return t


def git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=str(repo), capture_output=True, text=True, check=True)


def run_hook(repo: Path, mode: str, *extra: str) -> tuple[int, str]:
    env = dict(os.environ)
    env["BMOE_GOOSE_ART"] = mode
    p = subprocess.run([sys.executable, str(SCRIPT), *extra], cwd=str(repo), env=env,
                       capture_output=True, text=True, check=False)
    return p.returncode, p.stdout + p.stderr


def arm_end_to_end() -> Tally:
    """Staged trees: the same hook invocation in both modes must agree exactly."""
    t = Tally("FG663_ART_E2E")
    scenarios = [
        # name, path, body, extra args
        ("generated_over_limit", "gen/a.c", GENERATED_HEAD + b"y" * (1024 * 1024), ()),
        ("generated_at_limit", "gen/b.c", GENERATED_HEAD + b"y" * (1024 * 1024 - len(GENERATED_HEAD)), ()),
        ("generated_below_limit", "gen/c.c", GENERATED_HEAD, ()),
        ("handwritten_large", "src/big.c", b"int main(void) { return 0; }\n" + b"y" * (2 * 1024 * 1024), ()),
        ("generated_no_do_not_edit", "gen/d.c", b"/* Generated by the Goose compiler from a.goose.\nint x;\n", ()),
        ("banner_not_first_line", "gen/e.c", b"\n" + GENERATED_HEAD, ()),
        ("cuh_generated_dir", "gen/f.cuh", b"__device__ int x;\n", ()),
        ("cuh_upper_generated", "gen/Generated/g.cuh", b"__device__ int x;\n", ()),
        ("cuh_plain", "src/h.cuh", b"__device__ int x;\n", ()),
        ("goose_source", "src/i.goose", GENERATED_HEAD, ()),
        ("all_flag_below_limit", "gen/j.c", GENERATED_HEAD, ("--all",)),
        ("mb_two_below", "gen/k.c", GENERATED_HEAD + b"y" * (1024 * 1024 + 7), ("--mb", "2")),
        ("mb_two_at", "gen/l.c", GENERATED_HEAD + b"y" * (2 * 1024 * 1024 - len(GENERATED_HEAD)), ("--mb", "2")),
        ("mixed_tree", "gen/m.c", GENERATED_HEAD, ()),
    ]
    with tempfile.TemporaryDirectory() as td:
        repo = Path(td) / "repo"
        repo.mkdir()
        git(repo, "init", "-q")
        git(repo, "config", "user.email", "gate@example.com")
        git(repo, "config", "user.name", "gate")
        for name, rel, body, extra in scenarios:
            path = repo / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
            if name == "mixed_tree":
                # a second, larger generated file in the same index
                extra_path = repo / "gen" / "n.c"
                extra_path.write_bytes(GENERATED_HEAD + b"z" * (1024 * 1024))
                git(repo, "add", "gen/n.c")
            git(repo, "add", rel)
            rc_off, out_off = run_hook(repo, "0", *extra)
            rc_on, out_on = run_hook(repo, "1", *extra)
            t.rows += 1
            t.eq(t.rows, f"{name} exit", rc_off, rc_on)
            t.eq(t.rows, f"{name} output", out_off, out_on)
            git(repo, "rm", "-q", "--cached", rel)
            if name == "mixed_tree":
                git(repo, "rm", "-q", "--cached", "gen/n.c")
    return t


def main() -> int:
    mod = load_script()
    host = Host("art")
    try:
        a = arm_corpus(mod, host)
    finally:
        host.close()
    b = arm_end_to_end()
    rc = a.done() | b.done()
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
