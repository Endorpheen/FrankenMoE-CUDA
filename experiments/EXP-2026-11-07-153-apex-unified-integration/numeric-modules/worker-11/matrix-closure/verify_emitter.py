#!/usr/bin/env python3
"""Bind emitted gg_function ids for matrix-closure. Never guess.

Every matrix-closure export starts with `witness(...)`.  The verifier only
considers generated functions whose body calls fgc_witness, then binds each
one by its exact parameter-type sequence.  The result is written to
emitter_ids.json and emitter_ids.h for the CUDA shell.
"""
import hashlib, json, re, sys
from pathlib import Path

# name -> parameter type sequence without the trailing `int64_t base`
EXPECTED = {
    "entry":        "i,s,s,s,s,i,i,i,i",
    "mmvq_q8_block":"s,s",
    "mmq_q8_block": "s,s,i",
    "q8_elem":      "i,s,i,f,s,i",
    "mmvq_header":  "f,f,s,i",
    "mmq_header":   "f,f,i,s,i,i",
    "mmq_dot":      "i,s,i,s,i,s",
    "stage_weights":"i,s,i,i,i,i,s,i",
    "stage_q8":     "s,i,i,i,i,s",
    "sram_bound":   "i,i,i,s",
    "plan_mmq":     "i,i,i,i,i,i,i,s",
    "route_matmul": "i,i,i,i,i,i,i,i,s",
    "gemm_row":     "i,s,s,s,i,i,i,i,i",
}

def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def kind(t):
    t = t.strip().split()[0] if t.strip() else ""
    if t == "gg_slice": return "s"
    if t == "float": return "f"
    if t == "int64_t": return "i"
    if t == "uint64_t": return "u"
    raise ValueError("unexpected parameter type: " + t)

def bodies(text):
    lines = text.splitlines()
    out = {}
    i = 0
    while i < len(lines):
        m = re.match(r'^static .* gg_function_(\d+)\(.*\) \{', lines[i])
        if m:
            n = int(m.group(1))
            j = i + 1
            while j < len(lines) and lines[j] != "}":
                j += 1
            out[n] = "\n".join(lines[i:j+1])
            i = j
        i += 1
    return out

def main():
    here = Path(__file__).resolve().parent
    gen = here / "closure_generated.c"
    text = gen.read_text()
    bs = bodies(text)
    picked = {n: b for n, b in bs.items() if "fgc_witness(" in b}
    found = {}
    for name, want in EXPECTED.items():
        matches = []
        for n, body in picked.items():
            head = body.splitlines()[0]
            m = re.match(r'^static [^{]* gg_function_\d+\((.*)\) \{', head)
            if not m:
                continue
            params = [p.strip() for p in m.group(1).split(",")]
            if params and params[-1] == "int64_t base":
                params = params[:-1]
            try:
                key = ",".join(kind(p) for p in params)
            except ValueError:
                continue
            if key == want:
                matches.append(n)
        if len(matches) != 1:
            print(f"FAIL: {name} key {want} matched {matches}")
            for n, body in sorted(picked.items()):
                head = body.splitlines()[0]
                mm = re.match(r'^static [^{]* gg_function_\d+\((.*)\) \{', head)
                pp = [x.strip() for x in mm.group(1).split(",")] if mm else []
                if pp and pp[-1] == "int64_t base": pp = pp[:-1]
                try:
                    kk = ",".join(kind(x) for x in pp)
                except ValueError:
                    kk = "ERR"
                print(n, kk, head[:100])
            return 3
        found[name] = matches[0]
    if len(set(found.values())) != len(found):
        print("FAIL: duplicate emitter ids")
        return 4
    ids = sorted(picked)
    out = {
        "status": "PARSED_FROM_GENERATED_C",
        "generated_path": "matrix-closure/closure_generated.c",
        "generated_sha256": sha(gen),
        "exports": found,
        "witness_functions": ids,
        "note": "Only functions calling fgc_witness are exports; keys are exact parameter types.",
    }
    (here / "emitter_ids.json").write_text(json.dumps(out, indent=2) + "\n")
    hdr = ["// generated by verify_emitter.py; do not edit",
           "#pragma once"]
    for name, n in found.items():
        hdr.append(f"#define FGC_FN_{name.upper()} gg_function_{n}")
    hdr.append("")
    (here / "emitter_ids.h").write_text("\n".join(hdr))
    print(json.dumps({"status": out["status"], "exports": found}))
    return 0

if __name__ == "__main__":
    sys.exit(main())
