#!/usr/bin/env python3
"""Mechanical Goose-C -> CUDA qualifier adapter.

The frozen self-hosted compiler emits a portable C translation unit for each
Goose source file. This adapter:
  * drops the host runtime/prelude,
  * keeps the generated aggregate typedefs,
  * finds the single kernel function that `main` invokes,
  * keeps exactly its reachable `gg_function_*` closure,
  * re-qualifies those functions as `__device__` (device output) or leaves them
    as host functions (host output),
  * emits a stable, typed alias `apex_goose_<alias>` for the launcher layer.

It performs no semantic rewriting: function bodies, constants, arithmetic order
and bounds checks are byte-for-byte the compiler output.
"""
import argparse, hashlib, json, re, sys
from pathlib import Path

def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def find_functions(text):
    """Return {name: (start, end, ret, params, body)} for static gg_function_*."""
    out = {}
    pat = re.compile(r'(static\s+[A-Za-z_][A-Za-z0-9_ \*]*?)\b(gg_function_(\d+))\s*\(([^)]*)\)\s*\{')
    for m in pat.finditer(text):
        ret = m.group(1).strip()
        name = m.group(2)
        params = m.group(4).strip()
        # brace match from the opening brace
        i = m.end() - 1
        depth = 0
        in_str = False
        esc = False
        while i < len(text):
            c = text[i]
            if in_str:
                if esc:
                    esc = False
                elif c == '\\':
                    esc = True
                elif c == '"':
                    in_str = False
            else:
                if c == '"':
                    in_str = True
                elif c == '{':
                    depth += 1
                elif c == '}':
                    depth -= 1
                    if depth == 0:
                        i += 1
                        break
            i += 1
        body = text[m.end():i-1]
        out[name] = (m.start(), i, ret, params, body)
    return out

def strip_base(params):
    parts = [p.strip() for p in params.split(',') if p.strip()]
    assert parts and re.match(r'(const\s+)?int64_t\s+base$', parts[-1]), f'expected base tail in {params!r}'
    return parts[:-1]

def alias_source(ret, params, fname, alias, device):
    parts = strip_base(params)
    names = []
    for p in parts:
        toks = p.split()
        names.append(toks[-1])
    sig = ', '.join(parts)
    call_args = ', '.join(names + ['0'])
    if ret == 'void':
        call = f'    {fname}({call_args});'
        head = 'static __device__ void' if device else 'void'
    else:
        call = f'    return {fname}({call_args});'
        head = f'static __device__ {ret}' if device else ret
    return f'{head} apex_goose_{alias}({sig}) {{\n{call}\n}}\n'

def qualify(generated, alias, out_path, device, extra_includes, wrapper=None):
    text = Path(generated).read_text()
    marker = '} gg_globals;'
    pos = text.find(marker)
    if pos < 0:
        sys.exit('adapter: gg_globals marker not found')
    tail = text[pos + len(marker):]

    typedefs = [ln.strip() for ln in text.splitlines() if re.match(r'typedef struct \{.*\} gg_type_\d+;', ln.strip())]

    funcs = find_functions(tail)
    program = None
    for name, (s, e, ret, params, body) in funcs.items():
        if 'gg_program' in tail[max(0, s-200):s]:
            program = name
    # find main via gg_program body references
    mprog = re.search(r'static int gg_program\(int argc, char \*\*argv\)[\s\S]*?\n\}', tail)
    if not mprog:
        sys.exit('adapter: gg_program not found')
    calls = re.findall(r'\b(gg_function_\d+)\(', mprog.group(0))
    if not calls:
        sys.exit('adapter: main not called from gg_program')
    main = calls[0]

    # kernel = first gg_function called from main body
    main_body = funcs[main][4]
    kcalls = re.findall(r'\b(gg_function_\d+)\(', main_body)
    if not kcalls:
        sys.exit('adapter: main does not call a kernel')
    kernel = kcalls[0]

    # reachable closure
    keep = set()
    stack = [kernel]
    while stack:
        f = stack.pop()
        if f in keep: continue
        keep.add(f)
        for c in re.findall(r'\b(gg_function_\d+)\(', funcs[f][4]):
            if c in funcs and c not in keep:
                stack.append(c)

    qual = '__device__ ' if device else ''
    ret, params = funcs[kernel][2], funcs[kernel][3]
    assert ret.startswith('static ')
    ret = ret[len('static '):].strip()

    lines = []
    lines.append('// AUTO-GENERATED by worker-9/tools/qualify_cuda.py. Do not edit.')
    lines.append(f'// generated_c_sha256 {sha256(generated)}')
    lines.append(f'// alias apex_goose_{alias}')
    for inc in extra_includes:
        lines.append(f'#include "{inc}"')
    lines.append('')
    lines.extend(typedefs)
    lines.append('static struct { unsigned char dummy; } gg_globals;')
    lines.append('')
    for name in sorted(keep, key=lambda n: int(n.split('_')[-1])):
        r = funcs[name][2][len('static '):].strip()
        lines.append(f'static {qual}{r} {name}({funcs[name][3]});')
    lines.append('')
    for name in sorted(keep, key=lambda n: int(n.split('_')[-1])):
        s, e, r, p, b = funcs[name]
        r2 = r[len('static '):].strip()
        lines.append(f'static {qual}{r2} {name}({p}) {{')
        lines.append(b)
        lines.append('}')
        lines.append('')
    lines.append(alias_source(ret, params, kernel, alias, device))
    if device and wrapper:
        lines.append('')
        wrapper_text = Path(wrapper).read_text()
        lines.append(wrapper_text)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text('\n'.join(lines) + '\n')
    return {'generated': str(generated), 'generated_sha256': sha256(generated), 'alias': alias,
            'kernel': kernel, 'main': main, 'keep': sorted(keep)}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--generated', required=True)
    ap.add_argument('--alias', required=True)
    ap.add_argument('--device-out', required=True)
    ap.add_argument('--host-out', required=True)
    ap.add_argument('--summary', required=True)
    ap.add_argument('--wrapper', default=None)
    a = ap.parse_args()
    d = qualify(a.generated, a.alias, a.device_out, True, ['apex_device_primitives.cuh'], a.wrapper)
    h = qualify(a.generated, a.alias, a.host_out, False, ['apex_host_runtime.h'])
    summary = {'device': d, 'host': h}
    Path(a.summary).write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary))

if __name__ == '__main__':
    main()
