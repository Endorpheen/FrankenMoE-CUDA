#!/usr/bin/env python3
"""Extract the IQ dequantizer grid tables from the native ggml-common.h.

The dequantizers of this slice decode a code into fixed-point grid values with
four static tables: iq3xxs_grid (256 x u32), iq3s_grid (512 x u32),
iq2s_grid (1024 x u64) and iq1s_grid (2048 x u64). They are file-static in
libggml-base and cannot be linked from outside, so this script copies the
literal table bodies out of ggml-common.h into a generated C translation unit
with an accessor. The table text is a faithful copy; only the symbol names and
the sizes become explicit.

The quantizer constructors build a different, normalized copy of the same code
book, so they are not a substitute here: the dequantizers use these tables.

    python3 tests/make-tables.py <native ggml-common.h> <output.c>
"""
import re
import sys

TABLES = [
    ("uint32_t", "iq3xxs_grid", 256),
    ("uint32_t", "iq3s_grid", 512),
    ("uint64_t", "iq2s_grid", 1024),
    ("uint64_t", "iq1s_grid", 2048),
]


def extract(text, name):
    m = re.search(r"GGML_TABLE_BEGIN\(\w+,\s*" + name + r",\s*\w+\)\n(.*?)GGML_TABLE_END\(\)", text, re.S)
    if not m:
        raise SystemExit("table not found: " + name)
    body = m.group(1)
    values = re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)
    return values


def main():
    native, out = sys.argv[1], sys.argv[2]
    text = open(native, encoding="utf-8").read()

    chunks = []
    for ctype, name, size in TABLES:
        values = extract(text, name)
        if len(values) != size:
            raise SystemExit(f"{name}: expected {size} values, found {len(values)}")
        body = ",\n    ".join(", ".join(values[i:i + 8]) for i in range(0, len(values), 8))
        chunks.append(f"static const {ctype} tbl_{name}[{size}] = {{\n    {body},\n}};\n")

    accessors = r"""
/* which: 0 iq3xxs_grid, 1 iq3s_grid, 2 iq1s_grid, 3 iq2s_grid. */
uint64_t tbl_qd_iq3(int which, int i) {
    return which == 0 ? (uint64_t) tbl_iq3xxs_grid[i] : (uint64_t) tbl_iq3s_grid[i];
}

uint64_t tbl_qd_iq2(int which, int i) {
    return which == 2 ? tbl_iq1s_grid[i] : tbl_iq2s_grid[i];
}
"""

    header = "/* Generated by tests/make-tables.py from the native ggml-common.h.\n   Do not edit; rebuild with tests/build.sh. */\n#include <stdint.h>\n\n"
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(chunks) + accessors)
    print("wrote", out)


if __name__ == "__main__":
    main()
