#!/usr/bin/env python3
"""Extract the native decision bodies out of a llama.cpp tree for the gate.

The gate never uses a hand transcription. Every oracle source is cut out of the
file the port was written from and wrapped with the smallest set of shims a
header-only harness needs; the shims decide nothing, they echo the case
parameters back and return the constants the native body compares against.

  S1  the "determine vocab type" block of llama_vocab::impl::load
  S2  llama_vocab::impl::tokenizer_st_partition
  S3  string_strip from common/common.cpp

Enum names are parsed out of the native headers, so the canonical record the
gate compares carries native names and no hard-coded numbers.

Two extractions are made per gate run: one from the staged tree (after the
refactor) and one from the pristine reference copy. The gate compares them in
the OFF build and compares Goose against the staged one in the ON build.

Usage: make-native.py <llama-vocab.cpp> <common.cpp> <llama-vocab.h> <llama.h>
                      <out-dir> <tag>
"""
