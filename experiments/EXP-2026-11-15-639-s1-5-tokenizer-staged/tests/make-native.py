def cut_dispatch(text):
    start = text.index(DISPATCH_START)
    end = text.index(DISPATCH_END, start)
    body = text[start:end]
    # The "no vocab" arm returns from load(); the harness returns from the
    # wrapper instead of finishing the remaining members.
    body, n = re.subn(r'(?m)^(\s*)return(?: true)?;\s*$', r'\1goto done;', body)
    assert n == 1, n
    return body


def cut_partition(text):
    for sig in PARTITION_SIGS:
        if sig in text:
            start = text.index(sig)
            break
    else:
        raise SystemExit('tokenizer_st_partition not found')
    brace = text.index('{', start)
    depth = 0
    for i in range(brace, len(text)):
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return text[brace + 1:i]
    raise SystemExit('unbalanced braces in tokenizer_st_partition')


def cut_strip(text):
    for sig in STRIP_SIGS:
        if sig in text:
            start = text.index(sig)
            brace = text.index('{', start)
            depth = 0
            for i in range(brace, len(text)):
                c = text[i]
                if c == '{':
                    depth += 1
                elif c == '}':
                    depth -= 1
                    if depth == 0:
                        return text[brace + 1:i]
    raise SystemExit('string_strip not found')


def names_from(header_text, pattern):
    pairs = []
    for m in re.finditer(pattern, header_text):
        pairs.append((int(m.group(2)), m.group(1)))
    pairs.sort()
    values = [v for v, _ in pairs]
    if values != list(range(len(values))):
        raise SystemExit('non-contiguous enum values')
    return [n for _, n in pairs]


def tag_symbols(text, tag):
    for name in RENAME:
        text = re.sub(r'\b' + name + r'\b', name + '_' + tag, text)
    return text


def main():
    src = Path(sys.argv[1])
    common = Path(sys.argv[2])
    precon = Path(sys.argv[3])
    llamah = Path(sys.argv[4])
    out = Path(sys.argv[5])
    tag = sys.argv[6]
    text = src.read_text()
    out.mkdir(parents=True, exist_ok=True)

    vtypes = names_from(llamah.read_text(),
                        r'LLAMA_VOCAB_TYPE_([A-Z0-9_]+)\s*=\s*(\d+)')
    ptypes = names_from(precon.read_text(),
                        r'LLAMA_VOCAB_PRE_TYPE_([A-Z0-9_]+)\s*=\s*(\d+)')

    names = ['// Generated by tests/make-native.py from the native headers.',
             'const char * vocab_type_name_TAG(int t) {',
             '    switch (t) {']
    for i, n in enumerate(vtypes):
        names.append(f'        case {i}: return "{n}";')
    names += ['        default: return "?";', '    }', '}', '',
              'const char * pre_type_name_TAG(int p) {',
              '    switch (p) {']
    for i, n in enumerate(ptypes):
        names.append(f'        case {i}: return "{n}";')
    names += ['        default: return "?";', '    }', '}', '']
    names_text = '\n'.join(names)

    body = cut_dispatch(text)
    cpp = CPP_HEAD + body + CPP_TAIL
    cpp = cpp.replace('std::string format_record_TAG(',
                      names_text + 'std::string format_record_TAG(')

    pbody = cut_partition(text)
    sbody = cut_strip(common.read_text())

    files = {
        f'native-dispatch-{tag}.h':   HEADER,
        f'native-dispatch-{tag}.cpp': cpp,
        f'native-partition-{tag}.h':  PARTITION_HEADER,
        f'native-partition-{tag}.cpp': PARTITION_CPP_HEAD + pbody + PARTITION_CPP_TAIL,
        f'native-strip-{tag}.h':      STRIP_HEADER,
        f'native-strip-{tag}.cpp':    STRIP_CPP_HEAD +
            'std::string native_strip_' + tag + '(const std::string & str) {' +
            sbody + '}\n',
    }

    for name, content in files.items():
        (out / name).write_text(tag_symbols(content, tag).replace('TAG', tag))

    line0 = text[:text.index(DISPATCH_START)].count('\n') + 1
    print(f'source        {src}')
    print(f'sha256        {hashlib.sha256(text.encode()).hexdigest()}')
    print(f'dispatch      {len(body.splitlines())} native lines from line {line0}')
    print(f'partition     {len(pbody.splitlines())} native lines')
    print(f'strip         {len(sbody.strip().splitlines())} native lines')
    print(f'enums         {len(vtypes)} vocab types, {len(ptypes)} pre types')
    print(f'tag           {tag}')


if __name__ == '__main__':
    main()
