#!/usr/bin/env python3
"""Emit the full name sweep of the staged tree for the gate.

The hand-written cases in the smoke cover the interesting combinations; this
sweep covers *every* tokenizer model name and *every* pre-tokenizer name the
staged llama.cpp knows, so a name whose flags drift between the canon module
and this revision cannot pass unnoticed.

Usage: gen-cases.py <llama-vocab.cpp> <out.h>
"""
import re
import sys
from pathlib import Path


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    text = src.read_text()

    start = text.index('if (tokenizer_model == "no_vocab"')
    end = text.index('ml.get_key(LLM_KV_TOKENIZER_ADD_PREFIX,', start)
    block = text[start:end]

    models = sorted(set(re.findall(r'tokenizer_model == "([^"]+)"', block)))
    pres = sorted(set(re.findall(r'tokenizer_pre == "([^"]+)"', block)))

    lines = ['// Generated by tests/gen-cases.py from src/llama-vocab.cpp.',
             '// Every tokenizer model name and every pre-tokenizer name the',
             '// staged tree compares against, swept by the gate.',
             'static const char * const fg_sweep_models[] = {']
    for m in models:
        lines.append(f'    "{m}",')
    lines += ['};', '', 'static const char * const fg_sweep_pres[] = {']
    for p in pres:
        lines.append(f'    "{p}",')
    lines += ['};', '']

    out.write_text('\n'.join(lines))
    print(f'models      {len(models)}')
    print(f'pres        {len(pres)}')
    print(f'wrote       {out}')


if __name__ == '__main__':
    main()
